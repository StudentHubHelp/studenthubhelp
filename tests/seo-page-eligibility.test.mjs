import assert from 'node:assert/strict';
import { decidePageState, pageMeetsThreshold, pageStateKey, parentPath } from '../scripts/seo-page-eligibility.mjs';
assert.equal(pageMeetsThreshold({type:'cityCategory',listingCount:5}),true);
assert.equal(pageMeetsThreshold({type:'cityCategory',listingCount:4}),false);
assert.equal(pageMeetsThreshold({type:'areaCategory',listingCount:3,verifiedCount:1,profileComplete:true}),true);
assert.equal(pageMeetsThreshold({type:'areaCategory',listingCount:3,verifiedCount:0,profileComplete:true}),false);
assert.equal(pageMeetsThreshold({type:'areaCategory',listingCount:9,verifiedCount:9,profileComplete:false}),false);
assert.equal(pageMeetsThreshold({type:'areaHub',listingCount:6,categoryCount:3,profileComplete:true}),true);
assert.equal(pageMeetsThreshold({type:'areaHub',listingCount:8,categoryCount:2,profileComplete:true}),false);
const now='2026-11-28T12:00:00.000Z';
const buffer=decidePageState({type:'cityCategory',listingCount:4,previousState:{status:'index'},now});
assert.equal(buffer.status,'index'); assert.equal(buffer.reason,'hysteresis-buffer');
const grace=decidePageState({type:'cityCategory',listingCount:3,previousState:{status:'index'},now});
assert.equal(grace.status,'noindex-grace'); assert.equal(grace.sitemap,false);
const redirect=decidePageState({type:'cityCategory',listingCount:2,previousState:{status:'noindex-grace',belowThresholdSince:'2026-10-20T12:00:00.000Z'},now});
assert.equal(redirect.status,'redirect');
assert.equal(decidePageState({type:'cityCategory',listingCount:2,now}).status,'omit');
assert.equal(pageStateKey({type:'areaCategory',citySlug:'sikar',categorySlug:'library',areaSlug:'nawalgarh-road'}),'areaCategory|sikar|library|nawalgarh-road');
assert.equal(parentPath({type:'areaCategory',citySlug:'sikar',categorySlug:'library'}),'/sikar/library/');
console.log('SEO page eligibility tests passed.');
