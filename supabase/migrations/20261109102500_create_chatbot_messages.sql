-- Persist StudentHubHelp chatbot transcripts for the authenticated admin dashboard.
-- Guest and signed-in visitors may append messages; only active admins may read them.
BEGIN;

CREATE TABLE IF NOT EXISTS public.chatbot_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id uuid NOT NULL,
  visitor_id uuid NOT NULL,
  user_id uuid NULL REFERENCES auth.users(id) ON DELETE SET NULL,
  role text NOT NULL CHECK (role IN ('user', 'assistant')),
  content text NOT NULL,
  intent text NULL,
  category text NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS chatbot_messages_conversation_created_idx
  ON public.chatbot_messages (conversation_id, created_at);
CREATE INDEX IF NOT EXISTS chatbot_messages_created_idx
  ON public.chatbot_messages (created_at DESC);

ALTER TABLE public.chatbot_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS chatbot_messages_admin_read ON public.chatbot_messages;
CREATE POLICY chatbot_messages_admin_read
  ON public.chatbot_messages
  FOR SELECT TO authenticated
  USING ((SELECT public.is_admin()));

DROP POLICY IF EXISTS chatbot_messages_guest_insert ON public.chatbot_messages;
CREATE POLICY chatbot_messages_guest_insert
  ON public.chatbot_messages
  FOR INSERT TO anon
  WITH CHECK (user_id IS NULL);

DROP POLICY IF EXISTS chatbot_messages_user_insert ON public.chatbot_messages;
CREATE POLICY chatbot_messages_user_insert
  ON public.chatbot_messages
  FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()));

-- Explicit grants are required for newly-created public tables on the Supabase Data API.
REVOKE ALL ON TABLE public.chatbot_messages FROM anon, authenticated;
GRANT INSERT ON TABLE public.chatbot_messages TO anon, authenticated;
GRANT SELECT ON TABLE public.chatbot_messages TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.chatbot_messages_id_seq TO anon, authenticated;

COMMIT;
